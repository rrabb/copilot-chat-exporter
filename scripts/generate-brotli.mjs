import { build, transform } from 'esbuild';
import { createHash } from 'node:crypto';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { createListingCompressionLoader } from '../src/session/compressed-listing-loader.ts';

const require = createRequire(import.meta.url);
const check = process.argv.includes('--check');
const packageInfo = JSON.parse(await readFile(new URL('../node_modules/brotli-dec-wasm/package.json', import.meta.url), 'utf8'));
if (packageInfo.version !== '2.3.2')
  throw new Error('The Brotli decoder must match pinned version 2.3.2.');
const wasm = await readFile(require.resolve('brotli-dec-wasm/web/bg.wasm'));
const wasmHash = createHash('sha256').update(wasm).digest('hex');
if (wasmHash !== '79b29cb1790560f0a0f32b4a31d935e2782875e4a367fde23c81d986b327ec3f')
  throw new Error('The pinned Brotli WASM asset changed. Review the decoder and notices before updating its checksum.');
const license = await readFile(new URL('../node_modules/brotli-dec-wasm/LICENSE-MIT.txt', import.meta.url), 'utf8')
  + '\n' + await readFile(new URL('../docs/BROTLI-NOTICES.txt', import.meta.url), 'utf8');
const result = await build({
  stdin: {
    contents: `
      import { initSync, BrotliDecStream } from 'brotli-dec-wasm/web';
      export function decode(bytes, wasm, expected) {
        initSync({module:wasm});
        const stream = new BrotliDecStream();
        let result;
        try {
          result = stream.dec(bytes, expected + 1);
          if(result.code !== 1 || result.input_offset !== bytes.length)
            throw new Error('The Brotli payload is incomplete, invalid or has trailing data.');
          return result.buf;
        } finally {
          if(result) result.free();
          stream.free();
        }
      }`,
    resolveDir: fileURLToPath(new URL('..', import.meta.url)),
    sourcefile: 'brotli-browser-decoder.js',
  },
  bundle: true,
  format: 'iife',
  globalName: 'brotliDecoder',
  minify: true,
  charset: 'ascii',
  write: false,
  logLevel: 'silent',
});
const js = result.outputFiles[0].text.trim();
if (/<\/script/iu.test(js) || license.includes('-->'))
  throw new Error('Decoder assets cannot be embedded safely in HTML.');
const loaders = {};
for (const codec of ['gzip', 'brotli']) {
  const source = createListingCompressionLoader(codec, js);
  const { code } = await transform(source, { minify: true, charset: 'ascii', target: 'es2022', legalComments: 'none' });
  loaders[codec] = code.trim();
  if (/[^\x20-\x7e]/u.test(loaders[codec]) || /<\/script/iu.test(loaders[codec]))
    throw new Error('Compressed-report scripts must be single-line ASCII safe for inline HTML.');
}
const generated =
  `// Generated by scripts/generate-brotli.mjs from brotli-dec-wasm@2.3.2. Do not edit.\n` +
  `export const brotliDecoderScript = ${JSON.stringify(js)};\n` +
  `export const gzipListingLoader = ${JSON.stringify(loaders.gzip)};\n` +
  `export const brotliListingLoader = ${JSON.stringify(loaders.brotli)};\n` +
  `export const brotliWasmBase64 = ${JSON.stringify(wasm.toString('base64'))};\n` +
  `export const brotliWasmSha256 = ${JSON.stringify(wasmHash)};\n` +
  `export const brotliLicense = ${JSON.stringify(license)};\n`;
const target = new URL('../src/generated/brotli-decoder.ts', import.meta.url);
if (check) {
  const stored = await readFile(target, 'utf8');
  if (stored.replace(/\r\n/gu, '\n') !== generated)
    throw new Error('Generated report assets are stale or modified. Run npm run generate:brotli, review the diff, then verify again.');
} else {
  await mkdir(new URL('../src/generated/', import.meta.url), { recursive: true });
  await writeFile(target, generated);
}
